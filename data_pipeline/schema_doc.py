HEADER = """# Database schema: MLB pitcher performance agent

Generated by `data_pipeline/build_db.py` from `data/baseball.duckdb`. Do not edit by hand;
edit `data_pipeline/dictionary.py` and rebuild. The agent can also query the
`data_dictionary` table for the same information.

The database is opened read-only. All data was fetched offline; the agent never calls the
source websites live.

## Finding the right table

Use the most summarized table that answers the question. Each table has its own columns, so check
its column list below before using it.

| You need | Table |
|---|---|
| A pitcher's season | `pitcher_season` |
| One pitch type in a season | `pitcher_season_pitch_type` |
| A month | `pitcher_month` |
| A game | `pitcher_game` (no month column: use `game_date`) |
| Any other cut, such as home/away, batter side, count or inning | `pitches`, filtered by `pitcher` |
| ERA, FIP, WHIP, innings (`ip_decimal`), per-9 rates | `bref_pitching_standard`, per season only |
| WAR, RA9 | `bref_pitching_value`, per season only |
| Injuries and roster moves | `il_stints`, `transactions` |

## Working with `pitches`

- Each row is one pitch, so summary columns like `pitches`, `batters_faced`, `k_pct` and `xwoba` don't
  exist here. Build them from the metric definitions below.
- `launch_speed` and `launch_angle` are also recorded on foul balls. Filter `type = 'X'` for balls in play.
- Hard-hit rate is the share of balls in play with `launch_speed >= 95`.
- The pitcher is at home when `inning_topbot = 'Top'`. His team is `home_team` then, otherwise `away_team`.

## Join paths

- `pitches.pitcher = players.key_mlbam`
- `players.key_bbref = bref_pitching_standard.bref_id` (or use `bref_pitching_standard.mlbam_id` directly)
- `pitches.pitcher = il_stints.mlbam_id`
- `pitches.pitcher = transactions.mlbam_id`
- `pitches.pitcher = mlb_people.mlbam_id`
- Summary tables use `pitcher` (MLBAM id) and `season`.

## Metric definitions (used in all summary tables)

| Metric | Definition |
|---|---|
| batters_faced | rows where `events` is not null, excluding baserunning-only events (caught stealing, pickoffs, stolen bases, wild pitch, passed ball, truncated_pa) |
| k_pct | strikeouts (`strikeout`, `strikeout_double_play`) / batters_faced |
| bb_pct | walks (`walk`, `intent_walk`) / batters_faced |
| whiff_pct | sum(is_whiff) / sum(is_swing) |
| chase_pct | sum(is_chase) / pitches with zone 11-14 |
| zone_pct | sum(in_zone) / pitches |
| csw_pct | sum(is_csw) / pitches |
| woba | sum(woba_value) / sum(woba_denom) |
| xwoba | per PA with woba_denom = 1: estimated_woba_using_speedangle if ball in play (`type = 'X'`), else woba_value; / sum(woba_denom) |
| woba_minus_xwoba | woba - xwoba (positive = unlucky / bad defense behind the pitcher) |
| babip | mean babip_value over balls in play that are not home runs |
| hr_per_fb | home runs / batted balls with bb_type = 'fly_ball' |
| avg_velo_fastball | mean release_speed for pitch_type FF, SI, FC |
| run_value_total | sum(-delta_run_exp); positive = good for the pitcher |

All rates are fractions between 0 and 1 (multiply by 100 for percent).

## Known limits of the data

The agent must use these to say when the data cannot answer a question:

- No Stuff+, Location+, Pitching+, xFIP, or SIERA (FanGraphs metrics; we have no FanGraphs data).
- A metric with no column here and no definition in this document isn't in the data, such as barrels. Report it as a gap, not an approximation.
- No private medical information. IL notes are short public descriptions only.
- No data on mechanics changes, coaching, pitch grips, or training, except what pitch traits suggest indirectly.
- No minor league pitch-level data.
- Statcast covers {statcast_range}. Baseball Reference covers {bref_range}. MLB Stats API transactions cover {tx_range}.
- Spring training and postseason are excluded.
- IL stints are parsed from transaction text with a heuristic; always cite `placement_description`.
- Small samples: rates for fewer than ~100 pitches or ~50 batters faced are noisy.

## Tables
"""


def write_schema_doc(db_path) -> None:
    con = duckdb.connect(str(db_path), read_only=True)
    tables = [r[0] for r in con.execute(
        "SELECT table_name FROM information_schema.tables WHERE table_schema='main' ORDER BY 1"
    ).fetchall()]

    def rng(t, col="season"):
        if t not in tables:
            return "(not loaded)"
        lo, hi = con.execute(f"SELECT min({col}), max({col}) FROM {t}").fetchone()
        return f"{lo} to {hi}"

    out = [HEADER.format(statcast_range=rng("pitches"), bref_range=rng("bref_pitching_standard"),
                         tx_range=rng("transactions"))]
    for t in tables:
        n = con.execute(f"SELECT count(*) FROM {t}").fetchone()[0]
        if t in DATE_COL:
            dr = rng(t, DATE_COL[t])
        elif t in SEASON_TABLES:
            dr = "seasons " + rng(t)
        else:
            dr = "-"
        out.append(f"\n### `{t}`\n\n- Grain: {GRAIN.get(t, '')}\n- Rows: {n:,}\n"
                   f"- Date range: {dr}\n- Source: {SOURCES.get(t, '')}\n- Keys: {KEYS.get(t, '')}\n\n"
                   "| Column | Type | Description |\n|---|---|---|")
        for c, dtype, desc in con.execute(
                "SELECT column_name, data_type, description FROM data_dictionary "
                "WHERE table_name = ? ORDER BY rowid", [t]).fetchall():
            out.append(f"| `{c}` | {dtype} | {desc.replace('|', '/')} |")
    con.close()
    DOCS.mkdir(parents=True, exist_ok=True)
    p = DOCS / "schema.md"
    p.write_text("\n".join(out) + "\n", encoding="utf-8")
    log.info("wrote %s", p)
